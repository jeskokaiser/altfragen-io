import React, { useState, useEffect, useRef, useCallback } from 'react';
import { cn } from '@/lib/utils';
import { Check, X, ChevronDown, ChevronUp } from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import { ModelIcon, ModelName } from './ModelIcon';
import { Badge } from '@/components/ui/badge';
import { Tooltip, TooltipTrigger, TooltipContent, TooltipProvider } from '@/components/ui/tooltip';

interface AmbossAnswerProps {
  optionLetter: 'A' | 'B' | 'C' | 'D' | 'E';
  optionText: string;
  isCorrect: boolean;
  isRevealed: boolean;
  percentage: number | null; // For stats, e.g. 97, or null if no data
  onClick: () => void;
  explanation?: string;
  children?: React.ReactNode;
  wasAttempted?: boolean; // Whether this answer was tried but not yet revealed
  isSelected?: boolean; // Whether this specific answer was clicked by the user
  showPercentage?: boolean; // Whether to show percentage (premium feature)
  modelIcons?: ModelName[]; // Array of model names that chose this answer
  showUpgradePrompt?: boolean; // Whether to show upgrade prompt (free user reached limit)
  isAIGenerated?: boolean; // Whether this option was completely generated by AI (original was empty)
  onToggleExpandRef?: React.MutableRefObject<(() => void) | null>; // Ref to expose toggle function to parent
}

export const AmbossAnswer: React.FC<AmbossAnswerProps> = ({
  optionLetter,
  optionText,
  isCorrect,
  isRevealed,
  percentage,
  onClick,
  explanation,
  children,
  wasAttempted = false,
  isSelected = false,
  showPercentage = true,
  modelIcons = [],
  showUpgradePrompt = false,
  isAIGenerated = false,
  onToggleExpandRef,
}) => {
  const [isExpanded, setIsExpanded] = useState(false);
  const [wasRevealed, setWasRevealed] = useState(false);
  const hasAutoExpandedRef = useRef(false);
  const prevSelectedRef = useRef(false);
  const answerContainerRef = useRef<HTMLDivElement>(null);

  // Reset when moving to a new question
  useEffect(() => {
    if (!isRevealed && wasRevealed) {
      // Moving to a new question - reset everything
      setIsExpanded(false);
      setWasRevealed(false);
      hasAutoExpandedRef.current = false;
      prevSelectedRef.current = false;
    }
    if (isRevealed && !wasRevealed) {
      setWasRevealed(true);
    }
  }, [isRevealed, wasRevealed]);

  // Reset auto-expand ref when selection changes (user clicks a different answer)
  useEffect(() => {
    if (!isSelected && prevSelectedRef.current) {
      // This answer was previously selected but is no longer selected
      hasAutoExpandedRef.current = false;
    }
    prevSelectedRef.current = isSelected;
  }, [isSelected]);

  // Auto-expand when feedback is revealed for the selected answer, or when answer is selected (for wrong answers before reveal)
  useEffect(() => {
    if (isSelected && !hasAutoExpandedRef.current) {
      const hasCommentsContent = Boolean(explanation || children);
      const canExpand = hasCommentsContent || showUpgradePrompt;
      if (canExpand) {
        setIsExpanded(true);
        hasAutoExpandedRef.current = true; // Mark that we've auto-expanded for this selection
      }
    }
  }, [isRevealed, isSelected, explanation, children, showUpgradePrompt]);

  // Scroll answer option into view when it becomes expanded to ensure full AI comments are visible
  useEffect(() => {
    if (isExpanded && answerContainerRef.current) {
      // Use setTimeout to ensure the DOM has updated with the expanded content
      setTimeout(() => {
        const element = answerContainerRef.current;
        if (element) {
          const elementTop = element.getBoundingClientRect().top + window.pageYOffset;
          const offset = 100; // Offset to account for navbar and some padding
          window.scrollTo({
            top: elementTop - offset,
            behavior: 'smooth',
          });
        }
      }, 100);
    }
  }, [isExpanded]);

  const toggleExpand = useCallback(() => {
    const hasCommentsContent = Boolean(explanation || children);
    const canExpand = hasCommentsContent || showUpgradePrompt;
    if (canExpand) {
      setIsExpanded((prev) => !prev);
    }
  }, [explanation, children, showUpgradePrompt]);

  // Expose toggle function to parent via ref
  useEffect(() => {
    if (onToggleExpandRef) {
      onToggleExpandRef.current = toggleExpand;
    }
    return () => {
      if (onToggleExpandRef) {
        onToggleExpandRef.current = null;
      }
    };
  }, [onToggleExpandRef, toggleExpand]);

  const handleClick = () => {
    const hasCommentsContent = Boolean(explanation || children);
    const canExpand = hasCommentsContent || showUpgradePrompt;

    // Before reveal:
    // - If answer is NOT already selected/attempted: toggle expansion AND trigger answer selection (first click)
    // - If answer IS already selected/attempted: only toggle expansion (subsequent clicks to collapse/expand)
    if (!isRevealed) {
      if (canExpand) {
        setIsExpanded((prev) => !prev);
      }
      // Only call onClick() if this is the first time interacting with this answer
      // (not selected and not previously attempted)
      if (!isSelected && !wasAttempted) {
        onClick();
      }
      // If already selected/attempted, just toggle expansion (don't call onClick to avoid double-toggle)
      return;
    }

    // After reveal, only toggle expansion if there is content to show.
    toggleExpand();
    // When revealed and no comments, do nothing.
  };
  // One visual state per row: open, selected, correct, wrong. See docs/design-system.md, "Antwortzeile".
  const state: 'open' | 'selected' | 'correct' | 'wrong' | 'neutral' = isRevealed
    ? isCorrect
      ? 'correct'
      : wasAttempted
        ? 'wrong'
        : 'neutral'
    : wasAttempted
      ? 'wrong'
      : isSelected
        ? 'selected'
        : 'open';

  const rowClasses = {
    open: 'bg-card hover:bg-muted',
    neutral: 'bg-card hover:bg-muted',
    selected: 'bg-primary-subtle shadow-[inset_3px_0_0_hsl(var(--primary))]',
    correct: 'bg-success-subtle shadow-[inset_3px_0_0_hsl(var(--success))]',
    wrong: 'bg-danger-subtle shadow-[inset_3px_0_0_hsl(var(--danger))]',
  }[state];

  const letterClasses = {
    open: 'text-muted-foreground',
    neutral: 'text-muted-foreground',
    selected: 'text-primary-strong',
    correct: 'text-success-strong',
    wrong: 'text-danger-strong',
  }[state];

  const stateLabel = { correct: ', richtig', wrong: ', falsch', selected: ', gewählt' }[
    state as 'correct' | 'wrong' | 'selected'
  ];

  const hasCommentsContent = Boolean(explanation || children);
  const canExpand = hasCommentsContent || showUpgradePrompt;

  return (
    <div ref={answerContainerRef} className={cn('relative border-b last:border-b-0', rowClasses)}>
      <button
        type="button"
        data-training-answer
        onClick={handleClick}
        aria-expanded={canExpand ? isExpanded : undefined}
        aria-label={`Antwort ${optionLetter}: ${optionText}${stateLabel ?? ''}`}
        className="flex min-h-12 w-full items-center gap-3 py-3 pl-5 pr-4 text-left transition-colors focus-visible:ring-inset focus-visible:ring-offset-0"
      >
        <span
          aria-hidden="true"
          className={cn('w-4 shrink-0 text-center text-lg font-bold leading-none', letterClasses)}
        >
          {optionLetter}
        </span>
        <span className="flex min-w-0 grow flex-wrap items-center gap-2">
          <span className="text-base leading-normal">{optionText}</span>
          {isRevealed && isAIGenerated && (
            <Badge variant="secondary" className="px-1.5 py-0 font-mono text-[11px]">
              KI
            </Badge>
          )}
        </span>
        <span className="flex shrink-0 items-center gap-2">
          {isRevealed && showPercentage && modelIcons.length > 0 && (
            <span className="flex items-center gap-1">
              {modelIcons.map((model) => (
                <ModelIcon key={model} model={model} />
              ))}
            </span>
          )}
          {isRevealed && showPercentage && (
            <TooltipProvider>
              <Tooltip>
                <TooltipTrigger asChild>
                  <span className="min-w-[2.5rem] text-right text-sm tabular-nums text-muted-foreground">
                    {percentage !== null ? `${Math.round(percentage)} %` : '–'}
                  </span>
                </TooltipTrigger>
                <TooltipContent>
                  <p>
                    {percentage !== null
                      ? `Anteil der Nutzer, die diese Antwortoption zuerst gewählt haben`
                      : 'Keine Statistiken verfügbar'}
                  </p>
                </TooltipContent>
              </Tooltip>
            </TooltipProvider>
          )}
          {state === 'correct' && <Check aria-hidden="true" className="size-5 text-success" />}
          {state === 'wrong' && <X aria-hidden="true" className="size-5 text-danger" />}
          {canExpand &&
            (isExpanded ? (
              <ChevronUp aria-hidden="true" className="size-4 text-muted-foreground" />
            ) : (
              <ChevronDown aria-hidden="true" className="size-4 text-muted-foreground" />
            ))}
        </span>
      </button>
      {isExpanded && (
        // Clicking the open comments folds them again, as before; the button above is the keyboard path.
        <div onClick={toggleExpand} className="border-t bg-muted/60 text-sm">
          <div className="py-3 pl-12 pr-5">
            {hasCommentsContent && !showUpgradePrompt ? (
              <div className="space-y-4">
                {explanation && (
                  <div className="leading-relaxed [&_li]:mb-1 [&_ol]:ml-5 [&_ol]:list-decimal [&_p]:mb-2 [&_ul]:ml-5 [&_ul]:list-disc">
                    <ReactMarkdown>{explanation}</ReactMarkdown>
                  </div>
                )}
                {children}
              </div>
            ) : showUpgradePrompt ? (
              <p className="text-muted-foreground">
                Tägliches Limit für kostenlose KI-Kommentare erreicht.{' '}
                <a
                  href="/subscription"
                  className="font-semibold text-primary underline-offset-4 hover:underline"
                >
                  Jetzt upgraden
                </a>
              </p>
            ) : (
              <p className="text-muted-foreground">Keine KI-Kommentare verfügbar</p>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
